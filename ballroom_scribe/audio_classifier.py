"""Audio classification and segmentation service using PANNs."""

import collections
import dataclasses
import pathlib
from collections.abc import Generator, Iterable, Mapping

import numpy as np
from scipy.ndimage import binary_closing, binary_opening

import ballroom_scribe
import ballroom_scribe.models
import ballroom_scribe.utils


def _cut_beginning(audio_chunks: collections.deque[ballroom_scribe.models.AudioChunk], cutoff_samples: int) -> None:
    """Cuts the beginning of a deque of audio chunks to the cutoff time."""
    # Delete chunks that end before the cutoff.
    popped: ballroom_scribe.models.AudioChunk | None = None
    while audio_chunks:
        popped = audio_chunks.popleft()
        if popped.end_samples > cutoff_samples:
            break

    if popped is None:
        return

    # Truncate the first chunk.
    _, trimmed = popped.split(new_start_samples=cutoff_samples)
    audio_chunks.appendleft(trimmed)


def _cut_end(audio_chunks: collections.deque[ballroom_scribe.models.AudioChunk], cutoff_samples: int) -> None:
    """Cuts the end of a deque of audio chunks to the cutoff time."""
    # Delete chunks that start after the cutoff.
    popped: ballroom_scribe.models.AudioChunk | None = None
    while audio_chunks:
        popped = audio_chunks.pop()
        if popped.start_samples < cutoff_samples:
            break

    if popped is None:
        return

    # Truncate the last chunk.
    trimmed, _ = popped.split(new_start_samples=cutoff_samples)
    audio_chunks.append(trimmed)


class AudioClassifier:
    """Classifies audio chunks into speech, music, or other sound event segments."""

    type ThresholdMapping = Mapping[ballroom_scribe.models.AudioChunk.Classification, float]

    def __init__(self, device: str, thresholds: ThresholdMapping, min_segment_seconds: float):
        """Initializes the instance.

        Args:
            device: The PyTorch device on which to run PANN inference.
            thresholds: A mapping with classifications as keys and confidence thresholds as values. For each key, the
                PANN must have a confidence that is greater than the threshold for the audio chunk to receive that
                classification. Every possible classification must be included.
            min_segment_seconds: Minimum segment duration in seconds to absorb micro-pauses. If an audio chunk is
                shorter, it will be absorbed into the previous audio chunk.
        """
        # We don't need to check for `NONE` because `_classify_frames` doesn't use a threshold for it.
        for classification in ballroom_scribe.PannInferencer.CLASSIFICATIONS:
            if classification not in thresholds:
                raise ValueError(f"Thresholds must include a threshold for {classification.name}.")

        self._inferencer = ballroom_scribe.PannInferencer(device=device)
        self._thresholds = thresholds
        self._min_chunk_seconds = min_segment_seconds

    def classify(
        self,
        audio_chunks: Iterable[ballroom_scribe.models.AudioChunk],
        channel: int,
        cache_dir: pathlib.Path,
    ) -> Generator[ballroom_scribe.models.AudioChunk]:
        """Splits audio into chunks of speech, music, and other sounds.

        VRAM usage increases with the length of the audio being classified, so you may pass in an iterable of audio
        chunks instead of the whole audio at once. Each chunk will be classified serially, capping VRAM usage.

        Important: the audio chunks must be ordered by start time.

        Because the classification may be less reliable near the boundaries of the chunks, each chunk may overlap with
        the previous. However, it may not leave a gap in between or start before the previous. When an overlap is
        detected, the overlap region will be split evenly. For the first half, the classifications from the first chunk
        will be used, and for the second half, the classifications from the second chunk will be used.

        Because the resulting audio chunks are generated by the :meth:`ballroom_scribe.models.AudioChunk.split` method,
        they share memory with the original audio chunks. No copying is performed.

        Args:
            audio_chunks: The audio chunks to classify.
            channel: The audio channel from which `audio_chunks` were loaded.
            cache_dir: The directory in which inferences will be cached.

        Yields:
            The audio chunks, with the `classification` property set to something other than `UNKNOWN`.
        """
        previous_classified_chunks = collections.deque[ballroom_scribe.models.AudioChunk]()

        # `previous_classified_chunks[0]` is not necessarily the start time of the previous unclassified chunk
        # because `_cut_beginning` and boundary merging can change the start sample of the first element.
        # To get around this, track the start time of the previous unclassified chunk directly.
        previous_start_samples = 0

        for current_unclassified_chunk in audio_chunks:
            overlap_cutover: int | None = None
            if previous_classified_chunks:
                # Do this validation before the `_classify_chunk` call to fail fast.
                overlap_cutover = ballroom_scribe.utils.compute_overlap_cutover(
                    previous_start_samples,
                    previous_classified_chunks[-1].end_samples,
                    current_unclassified_chunk.start_samples,
                )

            # Because we allow the next audio chunk to overlap with all of this one, we need to store all the chunks.
            current_classified_chunks = collections.deque(
                self._classify_chunk(
                    audio_chunk=current_unclassified_chunk,
                    channel=channel,
                    cache_dir=cache_dir,
                )
            )

            if not current_classified_chunks:
                continue

            if previous_classified_chunks:
                # Trim the previous and current classified chunks at the midpoint.
                assert overlap_cutover is not None
                _cut_end(previous_classified_chunks, overlap_cutover)
                _cut_beginning(current_classified_chunks, overlap_cutover)

                # If the last classified chunk from the previous unclassified chunk has the same classification as the
                # first classified chunk from the current unclassified chunk, merge them across `overlap_cutover`.
                if previous_classified_chunks[-1].classification == current_classified_chunks[0].classification:
                    current_classified_chunks.appendleft(
                        previous_classified_chunks.pop() + current_classified_chunks.popleft()
                    )

                yield from previous_classified_chunks

            previous_classified_chunks = current_classified_chunks
            previous_start_samples = current_unclassified_chunk.start_samples

        yield from previous_classified_chunks

    def _classify_chunk(
        self,
        audio_chunk: ballroom_scribe.models.AudioChunk,
        channel: int,
        cache_dir: pathlib.Path,
    ) -> Generator[ballroom_scribe.models.AudioChunk]:
        """Runs the PANN on one audio chunk and segments it by classification.

        Args:
            audio_chunk: The audio chunk with the `classification` property set to `UNKNOWN`.
            channel: The audio channel from which `audio_chunk` was loaded.
            cache_dir: The directory in which inferences will be cached.

        Yields:
            Audio chunks with the `classification` property set. All of the chunks will share memory with `audio_chunk`.
        """
        if not audio_chunk:
            return

        # Split the audio chunk at the changes in classification.
        new_start_samples = audio_chunk.start_samples
        frames = self._inferencer.infer_chunk(audio_chunk=audio_chunk, channel=channel, cache_dir=cache_dir)
        sample_classifications_rle = self._classify_frames(
            frames=frames,
            num_samples=audio_chunk.duration_samples,
            sample_rate=audio_chunk.sample_rate,
        )
        for classification_np, duration_samples in sample_classifications_rle:
            new_start_samples += int(duration_samples)
            new_audio_chunk, audio_chunk = audio_chunk.split(new_start_samples=new_start_samples)
            yield dataclasses.replace(
                new_audio_chunk,
                classification=ballroom_scribe.models.AudioChunk.Classification(classification_np),
            )
        # `audio_chunk` should now be empty. Its start time should be the same as the original end time.

    def _classify_frames(
        self,
        frames: np.typing.NDArray[np.floating],
        num_samples: int,
        sample_rate: int,
    ) -> ballroom_scribe.models.RunLengthEncoding[ballroom_scribe.models.AudioChunk.ClassificationNumPy]:
        """Applies thresholds to per-category framewise probabilities and returns a sample-level RLE.

        Args:
            frames:
                The maximum framewise probabilities for each category. The shape is
                `(num_frames, len(PannInferencer.CLASSIFICATIONS))`.
            num_samples:
                The number of samples in the audio chunk. This is needed to figure out the number of samples per frame.
            sample_rate:
                The sample rate of the audio chunk in samples per second.

        Returns:
            A run-length encoding of the classification of each sample. The `lengths` property is the number of samples
                of the audio chunk that the classification changes at. The `values` property is the classification at
                that sample. The `values` property is an `IntEnum` that is converted to a NumPy array of `int`s. The
                `values` property is converted to `int`s because `IntEnum`s are not compatible with NumPy.
        """
        samples_per_frame = num_samples / frames.shape[0]
        frames_per_second = sample_rate / samples_per_frame
        min_frames = max(1, round(self._min_chunk_seconds * frames_per_second))

        # Build a 1-D window of `True` values whose length matches `self._min_chunk_seconds`.
        binary_structure = np.ones(min_frames, dtype=bool)

        combined_flags = np.zeros(
            frames.shape[0],
            dtype=ballroom_scribe.models.AudioChunk.Classification.NONE.numpy().dtype,
        )

        for i, classification in enumerate(ballroom_scribe.PannInferencer.CLASSIFICATIONS):
            raw_mask = frames[:, i] > self._thresholds[classification]

            # `binary_structure` slides the `min_frames`-wide window across `raw_mask` and fills in any `False` gap
            # (dropout) between two `True` segments that is shorter than `min_frames`.
            closed_mask = binary_closing(raw_mask, structure=binary_structure)

            # Now, `binary_structure` slides the same `min_frames`-wide window across `closed_mask` and erases any
            # isolated `True` burst that is shorter than `min_frames`.
            clean_mask = binary_opening(closed_mask, structure=binary_structure)

            combined_flags |= np.where(clean_mask, classification.numpy(), np.int8(0))

        # Use run-length encoding to find the frames at which the classification changes.
        frame_classifications_rle = ballroom_scribe.models.RunLengthEncoding[
            ballroom_scribe.models.AudioChunk.ClassificationNumPy
        ].from_ndarray(combined_flags)

        # Convert the frames to samples to get the samples at which the classification changes.
        return dataclasses.replace(
            frame_classifications_rle,
            lengths=np.diff(
                np.round(np.cumsum(frame_classifications_rle.lengths) * samples_per_frame), prepend=0
            ).astype(np.int64),
        )
